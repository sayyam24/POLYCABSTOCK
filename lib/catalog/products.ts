function makeSku(index: number, name: string): string {
  const slug = name
    .replace(/[^a-zA-Z0-9]/g, '')
    .slice(0, 12)
    .toUpperCase()
  return `ET-${String(index + 1).padStart(4, '0')}-${slug || 'ITEM'}`
}

export function getCatalogProducts(): Product[] {
  return CATALOG_ENTRIES.map((entry, index) => ({
    id: `prod_${String(index + 1).padStart(4, '0')}`,
    sku: makeSku(index, entry.name),
    ...entry,
  }))
}

